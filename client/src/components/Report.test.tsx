import { fireEvent, render, screen, within } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import type { Transaction } from '../api';
import Report from './Report';

const row = (date: string, amount: number, extra: Partial<Transaction> = {}): Transaction => ({ date, amount, type: 'expense', category: '식비', vendor: '', source: '', member: '효', ...extra });
afterEach(() => vi.useRealTimers());
describe('리포트 탭', () => {
  it('모바일 시험 화면에서 한 카테고리만 펼치고 다시 누르면 접는다', () => {
    vi.useFakeTimers({ shouldAdvanceTime: true }); vi.setSystemTime(new Date(2026, 10, 20));
    const data = [row('2026-10-01', 30000, { vendor: '마트' }), row('2026-10-02', 10000, { category: '교통', vendor: '버스' })];
    const { container } = render(<Report transactions={data} categories={[]} exclusions={{ income: [], expense: [] }} />);
    const buttons = container.querySelectorAll<HTMLButtonElement>('.rp-mobile-category > button');
    expect(buttons).toHaveLength(2);
    expect(buttons[0]).toHaveAttribute('aria-expanded', 'false');
    fireEvent.click(buttons[0]);
    expect(buttons[0]).toHaveAttribute('aria-expanded', 'true');
    expect(container.querySelector('.rp-mobile-vendors:not([hidden])')).toHaveTextContent('마트');
    fireEvent.click(buttons[0]);
    expect(container.querySelector('.rp-mobile-vendors:not([hidden])')).toBeNull();
    fireEvent.click(buttons[0]);
    fireEvent.click(buttons[1]);
    expect(buttons[0]).toHaveAttribute('aria-expanded', 'false');
    expect(buttons[1]).toHaveAttribute('aria-expanded', 'true');
    expect(container.querySelector('.rp-mobile-vendors:not([hidden])')).toHaveTextContent('버스');
    fireEvent.click(screen.getByRole('button', { name: '이전 달' }));
    expect(container.querySelector('.rp-mobile-vendors:not([hidden])')).toBeNull();
  });
  it('기간 이동과 선택한 카테고리의 증감·추세를 갱신한다', () => {
    vi.useFakeTimers({ shouldAdvanceTime: true }); vi.setSystemTime(new Date(2026, 10, 20));
    const data = [row('2026-09-01', 20000), row('2026-10-01', 30000), row('2026-10-02', 10000, { category: '교통' })];
    render(<Report transactions={data} categories={[]} exclusions={{ income: [], expense: [] }} />);
    expect(screen.getByText(/10,000원 증가 \(\+50.0%\)/)).toBeInTheDocument();
    expect(screen.getByLabelText('선택한 카테고리 월별 추세')).toHaveTextContent('식비');
    fireEvent.click(within(screen.getByRole('group', { name: '지출 카테고리 선택' })).getByRole('button', { name: /교통/ }));
    expect(screen.getByLabelText('선택한 카테고리 월별 추세')).toHaveTextContent('교통');
    expect(screen.getByText(/10,000원 증가/)).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: '이전 달' }));
    fireEvent.click(screen.getByRole('button', { name: '기간 선택' }));
    expect(screen.getByLabelText('월')).toHaveValue('9');
    fireEvent.change(screen.getByLabelText('월'), { target: { value: '10' } });
    expect(screen.getByRole('button', { name: '기간 선택' })).toHaveTextContent('10월');
    expect(screen.queryByRole('button', { name: '완료' })).not.toBeInTheDocument();
    fireEvent.pointerDown(document.body);
    expect(screen.queryByLabelText('월')).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: '연간' }));
    fireEvent.click(screen.getByRole('button', { name: '기간 선택' }));
    expect(screen.queryByLabelText('월')).not.toBeInTheDocument();
    fireEvent.keyDown(screen.getByLabelText('연도'), { key: 'Escape' });
    expect(screen.queryByLabelText('연도')).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: '이전 해' }));
    fireEvent.click(screen.getByRole('button', { name: '기간 선택' }));
    expect(screen.getByLabelText('연도')).toHaveValue('2025');
  });
  it('카테고리 선택 시 상단 추이와 오른쪽 거래처가 함께 바뀐다', () => {
    vi.useFakeTimers({ shouldAdvanceTime: true }); vi.setSystemTime(new Date(2026, 10, 20));
    const data = [row('2026-08-01', 1000, { vendor: '이전 거래' }), row('2026-10-01', 30000, { vendor: '마트' }), row('2026-10-02', 10000, { category: '교통', vendor: '버스' })];
    const { container } = render(<Report transactions={data} categories={[]} exclusions={{ income: [], expense: [] }} />);
    const head = container.querySelector('.trial-explorer-head') as HTMLElement;
    const detail = container.querySelector('.rp-explorer-detail') as HTMLElement;
    expect(within(head).getByRole('img', { name: '식비 최근 6개월 지출 추이' })).toBeInTheDocument();
    expect(head.querySelectorAll('.trial-mini-line')).toHaveLength(0);
    expect(within(detail).getByText('마트')).toBeInTheDocument();
    expect(within(detail).queryByLabelText('선택한 카테고리 월별 추세')).not.toBeInTheDocument();
    fireEvent.click(within(screen.getByRole('group', { name: '지출 카테고리 선택' })).getByRole('button', { name: /교통/ }));
    expect(within(head).getByRole('img', { name: '교통 최근 6개월 지출 추이' })).toBeInTheDocument();
    expect(within(detail).getByText('버스')).toBeInTheDocument();
    fireEvent.click(within(head).getByText('월별 금액 보기'));
    expect(within(head).getAllByText('데이터 없음').length).toBeGreaterThan(0);
  });
  it('월별 수입에서 지출을 뺀 차액을 부호와 함께 표시하고 기록 없는 달은 구분한다', () => {
    vi.useFakeTimers({ shouldAdvanceTime: true }); vi.setSystemTime(new Date(2026, 10, 20));
    const data = [row('2026-05-01', 100, { type: 'income' }), row('2026-05-02', 50), row('2026-06-01', 20, { type: 'income' }), row('2026-06-02', 60), row('2026-07-01', 10, { type: 'income' }), row('2026-07-02', 10), row('2026-10-01', 30)];
    const { container } = render(<Report transactions={data} categories={[]} exclusions={{ income: [], expense: [] }} />);
    expect(screen.getByLabelText('2026-05 차액 +50원')).toHaveTextContent('+50원');
    expect(screen.getByLabelText('2026-06 차액 −40원')).toHaveTextContent('−40원');
    expect(screen.getByLabelText('2026-07 차액 0원')).toHaveTextContent('0원');
    expect(screen.getByLabelText('2026-08 차액 데이터 없음')).toHaveTextContent('—');
    expect(within(container.querySelector('.trial-selected-summary') as HTMLElement).queryByText('선택한 항목')).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: '연간' }));
    expect(screen.getByLabelText('2026-05 차액 +50원')).toBeInTheDocument();
  });
  it('효·굥·공동·미지정 비교는 상단 개인 필터와 독립적이다', () => {
    vi.useFakeTimers({ shouldAdvanceTime: true }); vi.setSystemTime(new Date(2026, 10, 20));
    const data = [row('2026-10-01', 10), row('2026-10-01', 20, { member: '굥' }), row('2026-10-01', 30, { member: '공동' }), row('2026-10-01', 40, { member: undefined }), row('2026-10-01', 50, { category: '제외' })];
    render(<Report transactions={data} categories={[]} exclusions={{ income: [], expense: ['제외'] }} />);
    fireEvent.change(screen.getByLabelText('구성원'), { target: { value: '효' } });
    fireEvent.click(screen.getByRole('button', { name: '비교하기' }));
    const panel = screen.getByText('효·굥 함께 보기').closest('section') as HTMLElement;
    for (const name of ['효', '굥', '공동', '미지정']) expect(within(panel).getByRole('heading', { name })).toBeInTheDocument();
    expect(within(panel).queryByText('50원')).not.toBeInTheDocument();
  });
  it('개인 선택을 현재·이전 기간과 미승인 경고에 함께 적용한다', () => {
    vi.useFakeTimers({ shouldAdvanceTime: true }); vi.setSystemTime(new Date(2026, 10, 20));
    const data = [row('2026-09-01', 20000), row('2026-09-01', 40000, { member: '굥' }), row('2026-10-01', 30000, { vendor: '효거래처' }), row('2026-10-01', 60000, { member: '굥', vendor: '굥거래처' }), row('2026-10-01', 10000, { member: '공동' }), row('2026-10-01', 5000, { member: undefined }), row('2026-10-02', 1, { isVerified: false }), row('2026-10-02', 1, { member: '굥', isVerified: false })];
    const { container } = render(<Report transactions={data} categories={[]} exclusions={{ income: [], expense: [] }} />);
    const summary = () => within(container.querySelector('.rp-summary') as HTMLElement);
    expect(summary().getByText('105,000원')).toBeInTheDocument();
    fireEvent.change(screen.getByLabelText('구성원'), { target: { value: '효' } });
    expect(summary().getByText('30,000원')).toBeInTheDocument();
    expect(screen.getByRole('status')).toHaveTextContent('1건');
    expect(screen.getByText(/지난달보다 지출이/)).toHaveTextContent('10,000원 늘었어요');
    expect(screen.getByText('효거래처')).toBeInTheDocument();
    expect(screen.queryByText('굥거래처')).not.toBeInTheDocument();
    fireEvent.change(screen.getByLabelText('구성원'), { target: { value: '굥' } });
    expect(summary().getByText('60,000원')).toBeInTheDocument();
    expect(screen.getByText(/지난달보다 지출이/)).toHaveTextContent('20,000원 늘었어요');
  });
});
